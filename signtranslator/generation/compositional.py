"""Compositional sentence generation at inference time (round 15, stage 1; docs/NEXT_PHASE_PLAN.md, "Round 15
declared", 2026-10-28 14:59 UTC). No training: a sentence is signed as a sequence of words the prior learnt in
isolation, each generated by the prior itself.

**Word selection** (``select_words``; no evaluator is consulted):
- the training vocabulary is the set of English texts of the prior manifest's one-word (isolated-sign) train records
  (``training_vocabulary``: ``ISOLATED_CORPORA``, the records the training dataset serves), never a recogniser's labels;
- the sentence is normalised the way those texts are written (``normalise``): lower case, words of ``[a-z0-9]`` with
  internal apostrophes kept whole (curly and mis-decoded apostrophes read as straight ones), every other character,
  hyphens included, a word break ("e-mail" -> "e mail", as the corpora write E-MAIL);
- entries are matched greedily left to right, longest first (an entry may have several words: "thank you", "a lot");
  single-letter entries (ASLLVD's fingerspelled letters) are never matched (amendment 1: "I" read as the letter I);
- a token that starts no entry and is not a stop word is tried against the inflection fallback (amendment 1,
  ``inflection_candidates``), in the declared order: the plural forms (-s, -es, -ies -> -y), then -ing (the bare stem,
  the stem with a doubled final consonant undoubled, the stem with its dropped e restored), then -ed (the same three);
  the first candidate that is a (multi-letter) vocabulary entry is taken. No other mapping: contractions and digits
  stay unmatched; a token with no hit is dropped (out of vocabulary);
- matched entries in the declared stop-word list (articles, forms of be / do / have, "to", "of") are dropped, also
  when the fallback reached them ("doing" -> "do"); a multi-word entry is one sign and is kept whole even when it
  contains a stop word ("a lot", "next to");
- English order is kept. ``selection_details`` gives every token's fate (exact, fallback, stop word, unmatched) and
  ``selection_statistics`` the shares.

**Durations** (``fitted_durations``): word k gets ``max(floor, total * t_k / sum t)``, ``t_k`` its typical isolated
duration: the median ``continuous.seconds`` of its train records (the trimmed length the prior trained on; not
sampled) and ``total`` the sentence's reference duration (plus the frames the joins overlap, for crossfades).

**Modes** (``compose``):
- ``crossfade`` (V1): each word generated independently (``generate_rvq_motion`` at its fitted duration, then
  ``post``), joined by ``concatenate``'s overlap crossfade (the compositional baseline's join, moved here unchanged).
- ``chained`` (V2): each word is generated by the prior *continuing* the codes it generated for the previous words
  (``continue_from``, the prefix forms' sampler, moved here unchanged), with word k's text alone in the cross-attention.
  The clock and duration conditioning, and why: the prior conditions every step on its clock (seconds since the
  clip's first frame) and on the clip's total duration, through the phase ``seconds / duration``. Segment k is
  sampled exactly as a prefix continuation: the history is every earlier word's generated codes, the clock runs on
  uniformly from 0 over history and segment (so the segment's clock starts where the previous segment ended), and the
  duration input is the *cumulative* end of word k (``continue_from``'s ``count / 24``). So every forward pass sees a
  clip the prior could have been trained on: a uniform clock from 0 with its phase reaching 1 exactly at the end of
  word k, where an isolated training clip ends. The alternatives are out of distribution: word k's own duration with
  the continuing clock gives phases far above 1 for later words; a clock restarting at 0 for each word puts the
  history at negative or repeated times; the sentence's total duration gives every word but the last no end signal.
  The cost: word k starts at phase ``start_k / end_k`` (late words start near 1), a phase the isolated clips only see
  near their end.
- ``chained_trim`` (V3): ``chained``, and after each segment is generated, its leading and trailing rest frames are cut
  by the dominant-wrist activity rule of ``scripts/build_trimmed_word_manifest.py`` (``trim_window``, moved here
  unchanged) applied to the segment's decoded frames; the next word continues from the trimmed codes (one token per
  frame, so frames and codes are cut together). A segment the rule cannot trim (no window, a window under
  ``min_seconds``, an untracked arm) is kept whole, never dropped.
Every chained state is decoded from all its codes at once by the tokenizer (as a generation), then ``post``.
"""
from __future__ import annotations

from dataclasses import replace
import hashlib
import re
import statistics

import numpy as np

FPS = 24.
FLOOR = .3                         # seconds: the shortest fitted word duration (declared)
MODES = ("crossfade", "chained", "chained_trim")
ISOLATED_CORPORA = ("asllvd-text-v1", "rit-text-r6", "wlasl-text-r6", "semlex-text-v1")
# English function words ASL does not usually sign as separate lexical items (the compositional baseline's list,
# declared for round 15). Modals (can, will, should...) are kept: ASL signs them.
STOP_WORDS = frozenset({
    "a", "an", "the",                                            # articles
    "am", "is", "are", "was", "were", "be", "been", "being",     # be
    "do", "does", "did",                                         # do
    "have", "has", "had",                                        # have
    "to", "of",
})
# build_trimmed_word_manifest.py's defaults, which made the round-10 manifests (their "trim" block records them)
TRIM = dict(threshold=.1, margin=.25, min_tracked=.3, min_seconds=.5)
_TOKEN = re.compile(r"[a-z0-9]+(?:'[a-z0-9]+)*")
_APOSTROPHES = ("’", "‘", "ʼ", "â\u0080\u0099", "`")


# ---- word selection ----------------------------------------------------------------------------------------------

def normalise(text) -> list[str]:
    """The words of ``text`` as the isolated corpora write theirs: lower case, ``[a-z0-9]`` runs with internal
    apostrophes kept whole; anything else (hyphens, punctuation) separates words."""
    text = (text or "").lower()
    for a in _APOSTROPHES:
        text = text.replace(a, "'")
    return _TOKEN.findall(text)


def training_vocabulary(manifest, corpora=ISOLATED_CORPORA, partition: str = "train") -> dict[str, float]:
    """{entry: typical seconds} of the one-word records of ``corpora`` in ``partition`` that the training dataset
    serves (a text and usable continuous channels, as ``TextMotionDataset``): the entry is the normalised text
    (words joined by one space), the typical seconds the median of the records' ``continuous.seconds``."""
    from ..data_engineering.corpus_manifest import usable_channels
    seconds: dict[str, list[float]] = {}
    for r in manifest["records"]:
        if r.get("corpus") not in corpora or r.get("partition") != partition or not r.get("text"):
            continue
        if not usable_channels(r, "continuous"):
            continue
        entry = " ".join(normalise(r["text"]))
        s = (r.get("continuous") or {}).get("seconds")
        if entry and s:
            seconds.setdefault(entry, []).append(float(s))
    return {w: float(statistics.median(v)) for w, v in sorted(seconds.items())}


_VOWELS = frozenset("aeiou")


def inflection_candidates(token: str) -> list[str]:
    """The declared fallback forms of an out-of-vocabulary token, in order (duplicates removed): -s, -es, -ies -> -y;
    then -ing: stem, stem with a doubled final consonant undoubled, stem + e; then -ed: the same three (stem + e is
    the token without its final d: "used" -> "use"). Contractions and digits get none (declared: they stay
    unmatched)."""
    t, out = token, []
    if not t.isalpha():
        return []
    if t.endswith("s"):
        out.append(t[:-1])
    if t.endswith("es"):
        out.append(t[:-2])
    if t.endswith("ies"):
        out.append(t[:-3] + "y")
    for suffix in ("ing", "ed"):
        if t.endswith(suffix) and len(t) > len(suffix) + 1:
            stem = t[:-len(suffix)]
            out.append(stem)
            if len(stem) >= 2 and stem[-1] == stem[-2] and stem[-1] not in _VOWELS and stem[-1].isalpha():
                out.append(stem[:-1])
            out.append(stem + "e")
    return [c for k, c in enumerate(out) if c and c not in out[:k]]


def _matchable(entry: str, training_vocab) -> bool:
    """A vocabulary entry that may be matched: present, and not a single letter (amendment 1)."""
    return len(entry) > 1 and entry in training_vocab


def selection_details(text, training_vocab, stop_words=STOP_WORDS) -> list[dict]:
    """Every token span of the normalised text with its fate, in order: ``{"tokens", "entry", "kind"}``, kind one of
    "exact" (a vocabulary entry, kept), "fallback" (an inflection of a vocabulary entry, kept), "stop" (a stop word,
    dropped) or "unmatched" (dropped; entry None)."""
    tokens = normalise(text)
    longest = max((len(w.split(" ")) for w in training_vocab), default=0)
    rows, p = [], 0
    while p < len(tokens):
        for n in range(min(longest, len(tokens) - p), 0, -1):
            entry = " ".join(tokens[p:p + n])
            if _matchable(entry, training_vocab):
                rows.append(dict(tokens=tokens[p:p + n], entry=entry,
                                 kind="stop" if entry in stop_words else "exact"))
                p += n
                break
        else:
            t = tokens[p]
            if t in stop_words:
                rows.append(dict(tokens=[t], entry=None, kind="stop"))
            else:
                hit = next((c for c in inflection_candidates(t) if _matchable(c, training_vocab)), None)
                kind = "unmatched" if hit is None else "stop" if hit in stop_words else "fallback"
                rows.append(dict(tokens=[t], entry=hit, kind=kind))
            p += 1
    return rows


def select_words(text, training_vocab, stop_words=STOP_WORDS) -> list[str]:
    """The entries of ``training_vocab`` (any container of normalised entries) the text signs, in English order:
    greedy left-to-right matching, longest entry first, single letters never, the inflection fallback for tokens that
    start no entry; unmatched tokens and stop words dropped (``selection_details``)."""
    return [r["entry"] for r in selection_details(text, training_vocab, stop_words) if r["kind"] in KEPT]


KEPT = ("exact", "fallback")


def selection_statistics(details) -> dict:
    """Selection statistics over sentences (``details``: one ``selection_details`` list per sentence): words per
    sentence, the share of selected words matched by the fallback, and every token kind's share of the tokens."""
    words = [sum(r["kind"] in KEPT for r in rows) for rows in details]
    kinds = {k: sum(len(r["tokens"]) for rows in details for r in rows if r["kind"] == k)
             for k in ("exact", "fallback", "stop", "unmatched")}
    tokens = sum(kinds.values())
    fallback = sum(r["kind"] == "fallback" for rows in details for r in rows)
    return dict(sentences=len(details), empty_sentences=int(sum(w == 0 for w in words)), words_total=int(sum(words)),
                words_per_sentence_mean=round(float(np.mean(words)), 3) if words else None,
                words_per_sentence_median=float(np.median(words)) if words else None,
                fallback_words=int(fallback), fallback_share=round(fallback / sum(words), 4) if sum(words) else None,
                tokens=int(tokens), token_share={k: round(v / tokens, 4) if tokens else None for k, v in kinds.items()})


def fitted_durations(words, typical_seconds, total_seconds: float, floor: float = FLOOR) -> list[float]:
    """Each word's share of ``total_seconds`` in proportion to its typical isolated duration, at least ``floor``
    (words at the floor make the sum exceed the total)."""
    typical = [float(typical_seconds[w]) for w in words]
    if not typical:
        return []
    if min(typical) <= 0:
        raise ValueError("typical durations must be positive")
    return [max(floor, total_seconds * t / sum(typical)) for t in typical]


# ---- the crossfade join (moved unchanged from scripts/compositional_baseline.py) ----------------------------------

def crossfade_frames(seconds: float, fps: float = FPS) -> int:
    if seconds < 0:
        raise ValueError("crossfade must be >= 0 seconds")
    return int(round(seconds * fps))


def join_overlaps(lengths, frames: int) -> list[int]:
    """Overlap of each join: ``frames``, capped at half of either neighbour (so no clip is blended at both ends over
    the same frame, and a clip of one frame is hard-cut)."""
    return [min(frames, a // 2, b // 2) for a, b in zip(lengths[:-1], lengths[1:])]


def crossfade_weights(n: int) -> np.ndarray:
    """The second clip's weight on the n overlapping frames: (k + 1) / (n + 1)."""
    return (np.arange(n, dtype=np.float64) + 1) / (n + 1)


def _gram_schmidt(x: np.ndarray, eps: float = 1e-6):
    """(orthonormalised 6D columns, degenerate mask) of (..., 6) values."""
    a, b = x[..., 0:3], x[..., 3:6]
    na = np.linalg.norm(a, axis=-1, keepdims=True)
    a = a / np.clip(na, eps, None)
    b = b - (a * b).sum(-1, keepdims=True) * a
    nb = np.linalg.norm(b, axis=-1, keepdims=True)
    b = b / np.clip(nb, eps, None)
    return np.concatenate([a, b], -1), (na[..., 0] < eps) | (nb[..., 0] < eps)


def blend_values(kind: str, a: np.ndarray, b: np.ndarray, alpha: np.ndarray) -> np.ndarray:
    """(n, J, D) values on each channel's manifold: ``(1 - alpha) a + alpha b``, put back on the manifold; where that
    degenerates (antipodal unit vectors or rotations) the endpoint with the larger weight. ``alpha``: (n,)."""
    w = alpha.reshape(-1, *([1] * (a.ndim - 1)))
    v = (1 - w) * a + w * b
    if kind == "rotation_6d_columns":
        v, bad = _gram_schmidt(v)
    elif kind == "unit_vector":
        n = np.linalg.norm(v, axis=-1, keepdims=True)
        bad = n[..., 0] < 1e-6
        v = v / np.clip(n, 1e-6, None)
    else:
        return np.clip(v, 0., 1.) if kind == "bounded_scalar" else v
    nearer = np.where(w > .5, b, a)
    return np.where(bad[..., None], nearer, v)


def blend_channel(kind: str, ca, cb, alpha: np.ndarray) -> dict:
    """values, valid, observed, confidence of the crossfade of two channels' overlapping frames (same shapes)."""
    va, vb = ca.valid, cb.valid
    w = alpha[:, None]
    valid = va | vb
    values = blend_values(kind, ca.values, cb.values, alpha)
    values = np.where((va & ~vb)[..., None], ca.values, values)          # one side valid: that side, exactly
    values = np.where((vb & ~va)[..., None], cb.values, values)
    values = np.where(valid[..., None], values, 0.)
    wa, wb = (1 - w) * va, w * vb
    confidence = np.where(valid, (wa * ca.confidence + wb * cb.confidence) / np.where(valid, wa + wb, 1.), 0.)
    observed = valid & (~va | ca.observed) & (~vb | cb.observed)
    return dict(values=values, valid=valid, observed=observed, confidence=confidence)


def concatenate(states, overlap: int, *, fps: float = FPS, sample_id: str = "compositional"):
    """One state from ``states`` in order, joined by the overlap crossfade: consecutive clips overlap by ``overlap``
    frames (``join_overlaps``), blended with ``crossfade_weights`` per channel kind (``blend_channel``)."""
    from ..pose.multichannel import CHANNELS, MultichannelMotion
    if not states:
        raise ValueError("nothing to concatenate")
    lengths = [len(s.timestamps) for s in states]
    overlaps = join_overlaps(lengths, overlap)
    total = sum(lengths) - sum(overlaps)
    first = states[0]
    channels = {}
    for name, c0 in first.channels.items():
        kind = CHANNELS[name][0]
        group = [s.channels[name] for s in states]
        for c in group[1:]:
            for field in ("labels", "coordinate_frame", "units", "convention"):
                if getattr(c, field) != getattr(c0, field):
                    raise ValueError(f"{name}: clips differ in {field}")
        parts = {k: [] for k in ("values", "valid", "observed", "confidence")}
        for k, c in enumerate(group):
            start = overlaps[k - 1] if k else 0
            stop = lengths[k] - (overlaps[k] if k < len(group) - 1 else 0)
            for f in parts:
                parts[f].append(getattr(c, f)[start:stop])
            if k < len(group) - 1 and overlaps[k]:
                n, nxt = overlaps[k], group[k + 1]
                tail = replace(c, values=c.values[-n:], valid=c.valid[-n:], observed=c.observed[-n:],
                               confidence=c.confidence[-n:])
                head = replace(nxt, values=nxt.values[:n], valid=nxt.valid[:n], observed=nxt.observed[:n],
                               confidence=nxt.confidence[:n])
                for f, v in blend_channel(kind, tail, head, crossfade_weights(n)).items():
                    parts[f].append(v)
        valid = np.concatenate(parts["valid"])
        observed = np.concatenate(parts["observed"]) & valid
        methods = [c.inference_method for c in group if c.inference_method]
        method = methods[0] if methods else ("compositional crossfade" if (valid & ~observed).any() else None)
        channels[name] = replace(
            c0, values=np.where(valid[..., None], np.concatenate(parts["values"]), 0.).astype(c0.values.dtype),
            valid=valid, observed=observed,
            confidence=np.where(valid, np.concatenate(parts["confidence"]), 0.).astype(c0.confidence.dtype),
            source_id=f"compositional:{c0.source_id}",
            source_sha256=hashlib.sha256("|".join(c.source_sha256 for c in group).encode()).hexdigest(),
            inference_method=method)
        if len(valid) != total:
            raise AssertionError("concatenation length")
    timestamps = float(first.timestamps[0]) + np.arange(total, dtype=np.float64) / fps
    return MultichannelMotion(timestamps, first.clock_id, sample_id, channels)


def take_frames(state, index):
    """The frames ``index`` (an index array) of ``state`` as a new state on a uniform 24 fps clock from its start."""
    channels = {n: replace(c, values=c.values[index], valid=c.valid[index], observed=c.observed[index],
                           confidence=c.confidence[index]) for n, c in state.channels.items()}
    t = float(state.timestamps[0]) + np.arange(len(index), dtype=np.float64) / FPS
    return replace(state, timestamps=t, channels=channels)


# ---- the rest-trim rule (moved unchanged from scripts/build_trimmed_word_manifest.py) ------------------------------

def side_tracks(state):
    """Per side: (forearm tracked (T,), hand tracked (T,)); the forearm needs its upper arm too."""
    body = state.channels["body"]
    labels = list(body.labels)
    out = {}
    for side in ("Left", "Right"):
        arm = body.valid[:, labels.index(f"{side}Forearm")] & body.valid[:, labels.index(f"{side}UpperArm")]
        out[side] = (arm, state.channels[f"{side.lower()}_hand"].valid.all(axis=1))
    return out


def sign_window(heights: np.ndarray, tracked: np.ndarray, fps: float, threshold: float, margin: float):
    """(lo, hi) seconds from the first frame, or None when no frame is tracked."""
    if not tracked.any():
        return None
    h = heights[tracked]
    rest, peak = np.percentile(h, 10), np.percentile(h, 95)
    active = np.flatnonzero(tracked & (heights > rest + threshold * (peak - rest)))
    if not len(active):
        return None
    last = (len(heights) - 1) / fps
    return max(active[0] / fps - margin, 0.), min(active[-1] / fps + margin, last)


def trim_window(state, threshold: float = TRIM["threshold"], margin: float = TRIM["margin"],
                min_tracked: float = TRIM["min_tracked"], min_seconds: float = TRIM["min_seconds"], fps: float = FPS):
    """``build_trimmed_word_manifest``'s rule on one state at ``fps``: (window (lo, hi) seconds rounded to 4
    places, or None; reason "trimmed" / "arm_untracked" / "no_sign_window"). The dominant side is the one whose
    tracked wrist height above its shoulder varies most."""
    from .canonical_skeleton import skeleton_positions
    joints, pos, _ = skeleton_positions(state)
    tracks = side_tracks(state)
    best = None
    for side in ("Right", "Left"):
        ok = np.asarray(tracks[side][0], dtype=bool)
        h = pos[:, joints.index(f"{side}Hand"), 1] - pos[:, joints.index(f"{side}Shoulder"), 1]
        spread = float(np.ptp(h[ok])) if ok.any() else -1.
        if best is None or spread > best[0]:
            best = (spread, side, ok, h)
    _, side, ok, h = best
    if ok.mean() < min_tracked:
        return None, "arm_untracked"
    w = sign_window(h, ok, fps, threshold, margin)
    if w is None or w[1] - w[0] < min_seconds:
        return None, "no_sign_window"
    return (round(w[0], 4), round(w[1], 4)), "trimmed"


def window_frames(frames: int, lo: float, hi: float, fps: float = FPS) -> np.ndarray:
    """Indices of the frames a window keeps, as ``corpus_manifest.window_state`` keeps them on a uniform clock."""
    t = np.arange(frames, dtype=np.float64) / fps
    return np.flatnonzero((t >= lo - 1e-9) & (t <= hi + 1e-9))


# ---- the prior's sampling paths (moved unchanged from scripts/exposure_diagnostic.py) ----------------------------

def make_decode(tokenizer, motion_config, post):
    """``decode(codes (1, S, J), frames, text)``: the codes decoded and assembled as a generation (every trained channel
    valid), then ``post``."""
    import torch
    from .text_to_motion import assemble_state, native_values, unit_to_raw

    @torch.no_grad()
    def decode(codes, frames, text):
        unit = tokenizer.decode_codes(codes, frames)
        raw = unit_to_raw(motion_config, unit.double())
        native = native_values(motion_config, {key: v[0] for key, v in raw.items()})
        return post(assemble_state(motion_config, text, native, frames, 24., "diag:0", "diag-clock",
                                   method="motion_tokens_v2"))
    return decode


def continue_from(prior, tokenizer, decode, text, prefix, count, seed, *, guidance, device, greedy_fine=False,
                  temperature=None, return_codes=False):
    """Free run of ``count`` steps after the real codes ``prefix`` (1, k, J), as ``generate_rvq_motion`` samples.

    ``temperature`` (sentence diagnostic): None samples at 1, as the word diagnostic always has; a value or a mapping
    part -> value divides the guided logits as ``generate_rvq_motion`` does (code j belongs to part j mod P). With
    ``return_codes`` the (count, J) code sequence is returned with the state."""
    import torch
    from .motion_tokens import _empty_like
    from .text_to_motion import PAD, empty_loci, encode_texts, generation_loci
    P = len(tokenizer.parts)
    per_code = None
    if temperature is not None:
        names = [part for part, _ in tokenizer.parts]
        if isinstance(temperature, dict):
            unknown = set(temperature) - set(names)
            if unknown:
                raise ValueError(f"unknown parts in temperature: {sorted(unknown)}")
            per_code = [float(temperature.get(names[j % len(names)], 1.)) for j in range(prior.J)]
        else:
            per_code = [float(temperature)] * prior.J
    with torch.no_grad():
        config = prior.config
        tk, mk = (t.to(device) for t in encode_texts([text]))
        hid, _, mk = prior.encode(tk, mk, generation_loci(config, [text], None, device))
        empty = _empty_like(tk[:1, :2])
        e_hid, _, e_mask = prior.encode(empty, empty != PAD, empty_loci(config, device))
        seconds_out = torch.tensor([count / 24.], device=device)
        clock = (torch.arange(count, device=device, dtype=torch.float32) / 24.)[None]
        g = torch.Generator().manual_seed(seed)
        sequence = torch.cat((torch.full((1, 1, prior.J), prior.K, dtype=torch.long, device=device), prefix), 1)
        for k in range(prefix.shape[1], count):
            h = prior.temporal_states(hid, mk, sequence, clock[:, :k + 1], seconds_out)[:, -1]
            h_free = (prior.temporal_states(e_hid, e_mask, sequence, clock[:, :k + 1], seconds_out)[:, -1]
                      if guidance != 1. else None)
            step_codes = torch.zeros((1, 0), dtype=torch.long, device=device)
            for j in range(prior.J):
                logits = prior.depth_logits(h, step_codes)[:, -1]
                if h_free is not None:
                    free = prior.depth_logits(h_free, step_codes)[:, -1]
                    logits = free + guidance * (logits - free)
                if per_code is not None:
                    logits = logits / max(per_code[j], 1e-6)
                if greedy_fine and j >= P:                          # stage >= 2 of every part: its mode
                    choice = logits.argmax(-1, keepdim=True)
                else:
                    choice = torch.multinomial(torch.softmax(logits.float(), -1).cpu(), 1, generator=g).to(device)
                step_codes = torch.cat((step_codes, choice), 1)
            sequence = torch.cat((sequence, step_codes[:, None]), 1)
        state = decode(sequence[:, 1:], count, text)
    return (state, sequence[0, 1:].cpu()) if return_codes else state


# ---- composition -------------------------------------------------------------------------------------------------

def word_frames(seconds: float, fps: float = FPS) -> int:
    """Frames of a word generated for ``seconds`` (``generate_rvq_motion``'s rounding)."""
    return max(int(round(float(seconds) * fps)), 1)


def generate_word(prior, tokenizer, word: str, seconds: float, seed: int, *, guidance: float, temperature, post):
    """One isolated word at ``seconds`` exactly as the pilot's lexicon samples a word (``generate_rvq_motion``, top-k
    0, planned loci), resampled to 24 fps, then ``post`` (the accepted decoder gains and the pilot's head smoothing)."""
    from ..pose.resample import resample_motion
    from .motion_rvq import generate_rvq_motion
    raw = generate_rvq_motion(prior, tokenizer, [word], fps=FPS, durations=[seconds], guidance=guidance,
                              temperature=1. if temperature is None else temperature, seed=seed)[0]
    return post(resample_motion(raw, FPS))


def compose(prior, tokenizer, words, durations, mode: str, seeds, *, guidance: float, temperature, post,
            device=None, crossfade: int = 4, trim: dict | None = None, text: str | None = None):
    """(state, info) of one sentence signed as ``words`` (training-vocabulary entries, in order) at ``durations``
    (seconds each) by ``mode`` (module docstring); ``seeds`` one per word (crossfade: the word's sampler; chained: the
    segment's). ``post`` is the generator's post-processing (gains, head smoothing). ``info``: ``segments``, one row
    per word (frames generated, the clock span its step saw, the trim); for crossfade also ``clips``, the
    post-processed word clips (a reordering of them is the composition of the reordered words, seeds and durations)."""
    import torch
    if mode not in MODES:
        raise ValueError(f"unknown mode {mode!r}")
    if not words or len(words) != len(durations) or len(words) != len(seeds):
        raise ValueError("compose needs one duration and one seed per word, and at least one word")
    device = device if device is not None else next(prior.parameters()).device
    text = text if text is not None else " ".join(words)
    frames = [word_frames(d) for d in durations]
    if mode == "crossfade":
        clips = [generate_word(prior, tokenizer, w, d, s, guidance=guidance, temperature=temperature, post=post)
                 for w, d, s in zip(words, durations, seeds)]
        state = concatenate(clips, crossfade, sample_id=f"compositional-crossfade:{text[:40]}")
        rows = [dict(word=w, frames=len(c.timestamps), seed=s) for w, c, s in zip(words, clips, seeds)]
        return state, dict(mode=mode, segments=rows, clips=clips, frames=len(state.timestamps))
    if tokenizer.config.step != 1:
        raise ValueError("chained composition assumes one token per frame (tokenizer step 1)")
    trim = dict(TRIM, **(trim or {}))
    decode = make_decode(tokenizer, prior.config.tokenizer.motion, post)
    codes = torch.zeros((0, prior.J), dtype=torch.long)
    rows = []
    for w, f, s in zip(words, frames, seeds):
        start = codes.shape[0]
        chain, sequence = continue_from(prior, tokenizer, decode, w, codes[None].to(device), start + f, s,
                                        guidance=guidance, device=device, temperature=temperature, return_codes=True)
        row = dict(word=w, frames=f, seed=s, clock_start=start / FPS, duration_input=(start + f) / FPS)
        if mode == "chained_trim":
            segment = take_frames(chain, np.arange(start, start + f))
            window, reason = trim_window(segment, **trim)
            keep = window_frames(f, *window) if window is not None else np.arange(f)
            if not len(keep):                                       # cannot happen for a window inside the segment
                keep, reason = np.arange(f), "empty_window"
            sequence = torch.cat((sequence[:start], sequence[torch.as_tensor(start + keep, dtype=torch.long)]), 0)
            row.update(trim=reason, window=list(window) if window else None, kept=int(len(keep)),
                       kept_from=int(keep[0]), kept_to=int(keep[-1]))
        codes = sequence
        rows.append(row)
    state = decode(codes[None].to(device), codes.shape[0], text)
    state = replace(state, sample_id=f"compositional-{mode}:{text[:40]}")
    return state, dict(mode=mode, segments=rows, frames=int(codes.shape[0]), codes=codes)


